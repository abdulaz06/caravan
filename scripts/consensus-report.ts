// The group-plan generator on each demo crew, in every decision mode, as
// Markdown: the chosen dates with runners-up, the plan (day, slot, item,
// reasons) and everyone's satisfaction. Pure engine code — no database.
//   npx tsx scripts/consensus-report.ts > docs/CONSENSUS-DEMO.md
import { generatePlan, MODE_COPY, type ConsensusPlan, type DecisionMode } from "@/engine/consensus";
import { STAY_ID } from "@/engine/itinerary";
import { defaultRules } from "@/engine/rules";
import { createEngine, type Engine } from "@/engine/structure";
import { dayLabel, rangeLabel } from "@/lib/dates";
import { demoBallots, demoById } from "@/lib/demo-crew";
import { loadPreset } from "@/presets/registry";

const pct = (x: number | null) => (x === null ? "—" : `${Math.round(x * 100)}%`);
const cell = (s: string) => s.replace(/\|/g, "\\|");

function section(e: Engine, plan: ConsensusPlan, title: string): string {
  const out: string[] = [];
  const { catalog } = e;
  const name = (id: string) => (id === STAY_ID ? "Free time / stay in" : (catalog.byId[id]?.title ?? id));
  const people = new Map(plan.people.map((p) => [p.id, p.name]));
  out.push(`### ${title}`, "");
  const d = plan.dates;
  out.push(`**Dates:** ${rangeLabel(d.chosen.start, d.chosen.end)} · ${d.length} days (${d.lengthReason.toLowerCase()}) · ${d.chosen.full} of ${d.withDates} free for all of it, ${d.chosen.personDays} person-days.`, "");
  if (d.chosen.missing.length) out.push(`Missing days: ${d.chosen.missing.map((m) => `${people.get(m.id)} ${m.days.length}`).join(", ")}.`, "");
  out.push("Runners-up:", "");
  for (const w of d.runnersUp) {
    out.push(`- ${rangeLabel(w.start, w.end)} — ${w.full} free throughout, ${w.personDays} person-days; misses: ${w.missing.map((m) => `${people.get(m.id)} ${m.days.length}`).join(", ") || "nobody"}`);
  }
  out.push("", `**Mode:** ${MODE_COPY[plan.settings.mode].label} (floor K = ${plan.settings.floorK}, λ = ${plan.settings.lambda})`, "");
  out.push("| Day | Slot | Item | Reasons | Runner-up |", "|---|---|---|---|---|");
  for (const s of plan.slots) {
    s.items.forEach((it, i) => {
      const reasons = it.reasons.map((r) => r.text).join(" · ");
      const floor = it.floorFor.length ? ` (floor for ${it.floorFor.join(", ")})` : "";
      out.push(
        `| ${i === 0 ? `${s.day + 1} · ${dayLabel(s.date)}` : ""} | ${i === 0 ? catalog.preset.structure.slots[s.slot].label : "+ extra"} | ${cell(name(it.id))}${it.variant ? ` (${it.variant})` : ""} | ${cell(reasons + floor)} | ${it.runnerUp ? `${cell(name(it.runnerUp.id))} (${it.runnerUp.votes})` : ""} |`,
      );
    });
    if (s.split) out.push(`| | | ↳ split ${s.split.status}: ${s.split.a.votes} ${cell(name(s.split.a.id))} / ${s.split.b.votes} ${cell(name(s.split.b.id))} | ${s.split.both} picked both | |`);
  }
  out.push("", "| Traveller | Status | Days there | Picks in plan | Satisfaction | Added by the floor |", "|---|---|---|---|---|---|");
  for (const p of [...plan.people].sort((a, b) => (a.satisfaction ?? -1) - (b.satisfaction ?? -1))) {
    out.push(`| ${p.name} | ${p.status} | ${p.daysThere} | ${p.made.length} of ${p.picks} | ${pct(p.satisfaction)} | ${p.floorAdded || ""} |`);
  }
  const f = plan.fairness;
  out.push("", `Lowest ${pct(f.min)} · median ${pct(f.median)} · mean ${pct(f.mean)} · Jain's index ${f.index.toFixed(3)} · ${f.floorMet} of ${f.floorOf} got at least ${f.floor}. Budget ≈ $${plan.budget.perPerson[0]}–${plan.budget.perPerson[1]} per person${plan.budget.note ? ` (${plan.budget.note})` : ""}.`, "");
  if (plan.notes.length) out.push(`Notes: ${plan.notes.join(" ")}`, "");
  return out.join("\n");
}

const lines = [
  "# The group plan on the demo crews",
  "",
  "Generated by `npx tsx scripts/consensus-report.ts` — the consensus generator (docs/CONSENSUS.md) on each demo trip's fictional crew, in every decision mode (Custom at full fairness). Pure engine code: the same output every run.",
  "",
];
for (const id of ["sri-lanka", "georgia"]) {
  const { preset, catalog } = loadPreset(id);
  const e = createEngine(catalog, defaultRules(preset));
  const ballots = demoBallots(e, demoById(id)!);
  lines.push(`## ${preset.name} — ${ballots.length} travellers (${ballots.filter((b) => b.status === "submitted").length} submitted)`, "");
  const modes: [DecisionMode, number, string][] = [
    ["together", 0.5, "Everyone gets a say"],
    ["majority", 0.5, "Majority rules"],
    ["custom", 1, "Custom — slider at fairness"],
  ];
  for (const [mode, fairness, title] of modes) lines.push(section(e, generatePlan(e, ballots, { mode, fairness }), title));
}
console.log(lines.join("\n"));
