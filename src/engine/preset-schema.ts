// The TripPreset format: everything that makes a trip *that* trip — the
// destination, its day structure, the catalog of things to do, travel times,
// the map, costs, copy and theme — as plain JSON (presets/<id>/preset.json)
// validated by this schema. The engine reads presets only; no component or
// library knows about any particular destination.
//
// See docs/PRESETS.md for a guided tour and "How to add a destination".
import { z } from "zod";

// ── Building blocks ───────────────────────────────────────────────────

const id = z
  .string()
  .min(1)
  .max(64)
  .regex(/^[a-z0-9][a-z0-9-]*$/, "ids are lowercase letters, digits and dashes");
const isoDate = z.string().regex(/^\d{4}-\d{2}-\d{2}$/, "dates are YYYY-MM-DD");
const usdRange = z.tuple([z.number().min(0), z.number().min(0)]).refine(([lo, hi]) => lo <= hi, "a range is [low, high]");
const hexColor = z.string().regex(/^#[0-9a-fA-F]{6}$/, "colours are #rrggbb");
const latLng = z.tuple([z.number().min(-90).max(90), z.number().min(-180).max(180)]);

export const SLOTS = ["day", "night"] as const;
export const slotSchema = z.enum(SLOTS);

/** Catalog filter categories. Their meaning is fixed (family mode hides "party"); labels come from the preset. */
export const CATEGORY_IDS = ["adventure", "water", "nature", "culture", "food", "party", "chill"] as const;
export const categorySchema = z.enum(CATEGORY_IDS);

export const vibeSchema = z.union([z.literal(-2), z.literal(-1), z.literal(0), z.literal(1), z.literal(2)]);

export const sourceSchema = z.strictObject({ label: z.string().min(1), url: z.url() });

/** A photo after the photo pipeline has run (presets/<id>/photos.json). `src` is relative to the preset folder. */
export const photoSchema = z.strictObject({
  src: z.string().min(1),
  credit: z.string().min(1),
  source: z.url(),
  license: z.string().min(1),
  width: z.number().int().positive().optional(),
  height: z.number().int().positive().optional(),
  blurDataURL: z.string().startsWith("data:image/").optional(),
});

/** presets/<id>/photos.json: photo key → photos (first = cover). Generated by `npm run photos`. */
export const photoSetSchema = z.record(z.string(), z.array(photoSchema).min(1));

/** Words shown instead of copy that mentions drinks or nightlife, in family-friendly mode. */
const familyTextSchema = z
  .strictObject({
    title: z.string(),
    tagline: z.string(),
    loved: z.string(),
    description: z.string(),
    highlights: z.array(z.string()),
    goodToKnow: z.string(),
  })
  .partial();

/** One way of doing a multi-variant day trip (e.g. sunrise at the summit vs an easy morning). First = default. */
export const variantSchema = z.strictObject({
  id,
  title: z.string().min(1),
  emoji: z.string().min(1),
  summary: z.string().min(1),
  schedule: z.array(z.strictObject({ time: z.string(), text: z.string() })).min(1),
  /** Hours spent there (the drives come from the travel model). */
  hours: z.number().positive(),
  /** When the vehicle leaves base, e.g. "~12:30am". */
  leave: z.string().min(1),
  /** Door to door, e.g. "~14 hrs". */
  total: z.string().min(1),
  honest: z.array(z.string()),
  /** A soft note on the previous evening (never a lock). */
  eveBefore: z.string().optional(),
  /** A note on the same day's evening. */
  eveningNote: z.string().min(1),
});

// ── Activities ────────────────────────────────────────────────────────

/**
 * Anything that can sit in a Daytime or Evening slot:
 * - "option": curated, appears in A-vs-B matchups and the catalog (exactly one slot)
 * - "extra":  a small Quick extra, catalog only (may fit both slots)
 * - "family": a wholesome stand-in only shown in family-friendly mode
 */
export const activitySchema = z.strictObject({
  id,
  kind: z.enum(["option", "extra", "family"]),
  slots: z.array(slotSchema).min(1),
  /** Which pools (preset `areas`) it can be picked from. */
  areas: z.array(id).min(1),
  title: z.string().min(1),
  /** The place it happens (a preset region id). */
  region: id,
  /** Quick extras: who runs it ("Playdium, One Galle Face"). */
  venue: z.string().optional(),
  emoji: z.string().optional(),
  /** A custom illustration from the preset's illustration set (e.g. "hill-sun"). */
  icon: z.string().optional(),
  categories: z.array(categorySchema).min(1),
  tagline: z.string().min(1),
  /** "Why people love it", distilled from recent traveller reviews. */
  loved: z.string().min(1),
  description: z.string().min(1),
  highlights: z.array(z.string()).min(1),
  duration: z.string().min(1),
  /** Rough hours on the day, for slot time totals. */
  hours: z.number().positive(),
  /** Per person, USD. */
  estCostUsd: usdRange,
  /** -2 pure nature/adventure … +2 pure nightlife. */
  vibe: vibeSchema,
  intensity: z.enum(["easy", "moderate", "tough"]).optional(),
  tags: z.array(z.string()),
  /** Photo key in photos.json (defaults to the id). */
  photo: z.string().optional(),
  sources: z.array(sourceSchema),
  /** An honest caveat (seasonality, schedules…). */
  goodToKnow: z.string().optional(),
  /** Days of the week it runs (0 = Sun … 6 = Sat). Omit = every day. */
  availableDays: z.array(z.number().int().min(0).max(6)).min(1).max(6).optional(),
  /** A fun rules card (e.g. a pub-golf scorecard). */
  rules: z.strictObject({ title: z.string(), items: z.array(z.string()).min(1) }).optional(),
  /** A course of stops (e.g. pub golf holes). Par 0 = tee-off. */
  course: z.array(z.strictObject({ venue: z.string(), area: z.string(), par: z.number().int().min(0), note: z.string().optional() })).optional(),
  /** Stops on a scenic transfer route: km from the route's start. */
  routeKm: z.number().min(0).optional(),
  /** Nightlife items: the family-friendly stand-in (an activity id). */
  familySwap: id.optional(),
  /** Family-friendly wording for copy that mentions drinks or nightlife. */
  familyText: familyTextSchema.optional(),
  /** Only on a base's ordinary days (not the arrival or transfer day) — big day trips. */
  onlyBaseDays: z.boolean().optional(),
  /** Ways to do it, chosen when picked (stored as the pick's `variant`). */
  variants: z.array(variantSchema).min(2).optional(),
  /** What to pack. */
  bring: z.array(z.string()).optional(),
  /** Extras that only make sense alongside another pick in the same slot. */
  onlyWith: id.optional(),
  /** A quoted round-trip vehicle price (per vehicle), instead of the hourly estimate. */
  vehicleRoundTripUsd: usdRange.optional(),
});

export const pairSchema = z.strictObject({
  id,
  slot: slotSchema,
  /** The pool it's offered in. */
  area: id,
  a: id,
  b: id,
  theme: z.string().optional(),
  /** Offered only on a special date (preset `specialDates` id), pinned to it. */
  special: id.optional(),
});

// ── Places & travel ───────────────────────────────────────────────────

export const regionSchema = z.strictObject({
  id,
  name: z.string().min(1),
  short: z.string().min(1),
  lat: z.number().min(-90).max(90),
  lng: z.number().min(-180).max(180),
  /** For organizers and docs; never shown in family-friendly mode. */
  blurb: z.string(),
  /** Photo keys to try in order (first with photos wins). */
  photos: z.array(z.string()).min(1),
});

export const legSchema = z.strictObject({
  from: id,
  to: id,
  title: z.string().min(1),
  hours: z.number().positive(),
  label: z.string().min(1),
  detail: z.string().optional(),
  /** Per vehicle; split across the group in the budget. */
  vehicleCostUsd: usdRange,
});

export const routeSchema = z.strictObject({
  /** Base region at each end. */
  from: id,
  to: id,
  /** Towns along it with km from the start, in order. */
  stops: z.array(z.strictObject({ region: id, km: z.number().min(0) })).min(2),
  /** "along the coast" */
  label: z.string().min(1),
});

// ── Day structure ─────────────────────────────────────────────────────

export const baseSchema = z.strictObject({
  id,
  name: z.string().min(1),
  /** Where you sleep (for drive times). */
  region: id,
  /** The pool its days draw from. */
  area: id,
  nights: z.strictObject({ default: z.number().int().min(1), min: z.number().int().min(1), max: z.number().int().min(1) }),
  /** "Four nights on the south coast: fort, beaches, whales" — use {nights} for the number. */
  tagline: z.string().min(1),
  covers: z.string().min(1),
  photo: z.string().min(1),
  /** The name of an ordinary day here ("Galle base"). */
  dayName: z.string().min(1),
  /** The first base's first day ("Land in Colombo"). */
  arrivalName: z.string().optional(),
  /** A ribbon on this base's arrival day: {nights} is replaced. */
  arrivalNote: z.strictObject({ one: z.string(), many: z.string() }).optional(),
  /** Whole days here can be dragged into a new order. */
  reorderable: z.boolean().default(true),
  /** Free-date trips: this base's share of the nights (default: its default nights). */
  weight: z.number().positive().optional(),
  /** Free-date trips: the fewest nights worth stopping here for — a shorter trip skips this base (default: nights.min). The first base is always kept. */
  minNights: z.number().int().min(1).optional(),
  /** The way to the airport when the trip ends here (default: structure.departure.leg). */
  departureLeg: id.optional(),
});

export const transferSchema = z.strictObject({
  from: id,
  to: id,
  /** "Road trip to Galle" */
  name: z.string().min(1),
  /** The pool for the transfer day's daytime (stops on the way); omit = the destination's pool. */
  dayArea: id.optional(),
  /** Leg ids: straight there, and the scenic version used when stops are picked. */
  leg: id,
  scenicLeg: id.optional(),
  /** Route for the stops strip (preset `travel.routes`). */
  route: id.optional(),
});

export const areaSchema = z.strictObject({
  id,
  /** "Galle area", "On the way" */
  name: z.string().min(1),
  /** The base you set off from (drive times, "~45 min from Galle"). */
  home: id,
  /** Single picks can move between days that share this pool. */
  movable: z.boolean().default(false),
});

const stayInCopySchema = z.strictObject({
  title: z.string().min(1),
  tagline: z.string().min(1),
  description: z.string().min(1),
  highlights: z.array(z.string()).min(1),
  photos: z.array(z.string()).min(1),
  /** Shown under the title ("No travel", "~2 hrs on the expressway"). */
  meta: z.string().min(1),
  familyText: familyTextSchema.optional(),
});

export const specialDateSchema = z.strictObject({
  id,
  /** Month-day, e.g. "12-31". */
  date: z.string().regex(/^\d{2}-\d{2}$/),
  name: z.string().min(1),
  short: z.string().min(1),
  slot: slotSchema,
  /** The special pair per pool. */
  pairs: z.record(z.string(), id),
  intro: z.string().min(1),
  /** When it lands on the fly-home day. */
  departureNote: z.string().min(1),
  calendarNote: z.string().min(1),
});

// ── Choices on the preferences step ───────────────────────────────────

const choiceId = z.string().min(1).max(32).regex(/^[a-z0-9][a-z0-9_-]*$/, "choice ids are lowercase letters, digits, dashes and underscores");
const choice = z.strictObject({ id: choiceId, label: z.string().min(1), hint: z.string().optional() });
const choices = z.array(choice).min(1);

export const preferencesSchema = z.strictObject({
  budgets: z.array(choice.extend({ usd: z.tuple([z.number().min(0), z.number().min(0).nullable()]) })).min(1),
  stays: choices,
  sharedRooms: choices,
  interests: choices,
  earlyMornings: choices,
  transport: choices,
  dietary: choices,
  flexibility: choices,
});

// ── Theme ─────────────────────────────────────────────────────────────

const scale = <K extends string>(keys: readonly K[]) => z.strictObject(Object.fromEntries(keys.map((k) => [k, hexColor])) as Record<K, typeof hexColor>);

export const PALETTE_SCALES = {
  primary: ["950", "900", "800", "700", "600", "500", "300", "100"],
  secondary: ["900", "800", "700", "600", "400", "100"],
  accent: ["700", "600", "500", "300", "100"],
  highlight: ["600", "500", "400", "200", "100"],
  pop: ["600", "500", "300", "100"],
  night: ["950", "900", "800", "700"],
  surface: ["50", "100", "200", "300", "400"],
} as const;

export const FONT_IDS = ["fraunces", "instrument", "playfair", "bricolage", "dm-serif"] as const;
export const ILLUSTRATION_SETS = ["tropical", "alpine"] as const;

export const themeSchema = z.strictObject({
  palette: z.strictObject({
    primary: scale(PALETTE_SCALES.primary),
    secondary: scale(PALETTE_SCALES.secondary),
    accent: scale(PALETTE_SCALES.accent),
    highlight: scale(PALETTE_SCALES.highlight),
    pop: scale(PALETTE_SCALES.pop),
    night: scale(PALETTE_SCALES.night),
    surface: scale(PALETTE_SCALES.surface),
    paper: hexColor,
    ink: z.strictObject({ "1": hexColor, "2": hexColor, "3": hexColor }),
  }),
  fonts: z.strictObject({ display: z.enum(FONT_IDS), body: z.enum(FONT_IDS) }),
  illustrations: z.enum(ILLUSTRATION_SETS),
  /** One colour per day on the route map and share images. */
  dayColors: z.array(hexColor).min(4),
  confetti: z.array(hexColor).min(3),
});

// ── The preset ────────────────────────────────────────────────────────

export const presetSchema = z.strictObject({
  $schema: z.string().optional(),
  id,
  /** Bump when the format of saved picks changes (ids renamed, etc.). */
  version: z.number().int().min(1),
  name: z.string().min(1),
  destination: z.strictObject({
    country: z.string().min(1),
    /** IANA zone, e.g. "Asia/Colombo". */
    timezone: z.string().min(1),
    /** "Sri Lanka, your way." on the poster: plain + italic accent. */
    headline: z.tuple([z.string(), z.string()]),
    tagline: z.string().min(1),
    /** The tagline in family-friendly mode, if the plain one mentions nightlife. */
    familyTagline: z.string().optional(),
    /** "Dec 2026 – Jan 2027" */
    season: z.string().min(1),
    blurb: z.string().min(1),
    heroPhoto: z.string().min(1),
    /** Said on the fly-home day ("Ayubowan, Sri Lanka 🙏"). */
    farewell: z.string().min(1),
    /** Text around the submit stamp ("SEE YOU IN LANKA"). */
    stampText: z.string().min(1),
    /** Activity ids for the welcome page's photo strip (defaults to the first options with photos). */
    showcase: z.array(id).optional(),
    /** The welcome page's closing question, plain + italic ("Whales or wrecks?", "Jungle party or Pub Golf?"). */
    teaser: z.tuple([z.string(), z.string()]).optional(),
  }),
  currency: z.strictObject({
    /** The destination's currency (shown first in the picker). */
    local: z.string().length(3),
    default: z.string().length(3),
  }),
  dates: z.strictObject({
    /** Default date window organizers can change within `outer`. */
    window: z.strictObject({ start: isoDate, end: isoDate }),
    outer: z.strictObject({ start: isoDate, end: isoDate }),
    /** Free-date trips: the shortest and longest trip anyone can pick, in days (organizers can change it). */
    length: z.strictObject({ min: z.number().int().min(1), max: z.number().int().min(1).max(30) }).default({ min: 1, max: 14 }),
    /** A gentle "Most groups do 5–7 days" hint (days). */
    recommended: z.strictObject({ min: z.number().int().min(1), max: z.number().int().min(1).max(30) }).optional(),
  }),
  structure: z.strictObject({
    bases: z.array(baseSchema).min(1),
    arrival: z.strictObject({ leg: id, label: z.string().default("Land") }),
    transfers: z.array(transferSchema),
    departure: z.strictObject({
      name: z.string().min(1),
      short: z.string().min(1),
      leg: id,
      text: z.string().min(1),
    }),
    /** A shorter "preview" length with one night less at the last base. */
    preview: z.boolean(),
    slots: z.strictObject({
      day: z.strictObject({ label: z.string(), limitHours: z.number().positive() }),
      night: z.strictObject({ label: z.string(), limitHours: z.number().positive() }),
    }),
    /** How far (hours, one way) an extra may be from the slot's main item or the base: a group plan never adds a far-off extra. */
    extraRadiusHours: z.number().positive().max(3).default(0.75),
  }),
  areas: z.array(areaSchema).min(1),
  regions: z.array(regionSchema).min(2),
  travel: z.strictObject({
    /** Known drive times (hours) that beat the distance estimate. */
    known: z.array(z.tuple([id, id, z.number().positive()])),
    /** Estimate = straight-line km × detour ÷ kmh + overhead, rounded to the quarter hour. */
    estimate: z.strictObject({ detour: z.number().min(1), kmh: z.number().positive(), overhead: z.number().min(0) }),
    legs: z.record(z.string(), legSchema),
    routes: z.record(z.string(), routeSchema).default({}),
    /** "van" / "rental car" — used in copy. */
    vehicle: z.string().min(1),
    /** Whether the group drives itself (copy and budget lines). */
    selfDrive: z.boolean().default(false),
  }),
  map: z.strictObject({
    /**
     * Equirectangular projection: x = (lng - minLng) × scale × xScale + pad, y = (maxLat - lat) × scale + pad.
     * xScale ≈ cos(latitude) keeps places far from the equator from looking stretched (1 = none).
     */
    projection: z.strictObject({
      minLng: z.number(),
      maxLat: z.number(),
      scale: z.number().positive(),
      pad: z.number().min(0),
      xScale: z.number().positive().max(1).default(1),
    }),
    width: z.number().positive(),
    height: z.number().positive(),
    /** Simplified outline paths (SVG, projected). */
    outline: z.array(z.string().min(1)).min(1),
    /** Full-resolution outline for the zoomed map and share images. */
    detail: z.string().min(1),
    /** Neighbouring land (projected path), drawn muted so a land border doesn't read as coast. */
    surroundings: z.string().optional(),
    /** The default frame: two corners [lat, lng]. Grows to fit every stop. */
    focus: z.tuple([latLng, latLng]),
    /** Towns along a road, in order: legs between two of them follow it. */
    chains: z.array(z.array(id).min(2)),
    /** Roads drawn as driven between two towns ([lat, lng] waypoints from → to). */
    roads: z.array(z.strictObject({ from: id, to: id, via: z.array(latLng).min(1) })).default([]),
    /** Labels for towns south of this latitude go above their dot (e.g. a south coast with the sea below). */
    labelsAboveSouthOf: z.number().optional(),
    /** Name of the land mass in labels ("Sri Lanka"). */
    label: z.string().min(1),
    /** A body of water to name on the share images, set vertically at [lat, lng] ("Indian Ocean"). */
    waterLabel: z.strictObject({ text: z.string().min(1), at: latLng }).optional(),
  }),
  stayIn: z.strictObject({ day: stayInCopySchema, night: stayInCopySchema, transfer: stayInCopySchema.optional() }),
  specialDates: z.array(specialDateSchema).default([]),
  categories: z.array(z.strictObject({ id: categorySchema, label: z.string(), emoji: z.string() })).min(1),
  activities: z.array(activitySchema).min(1),
  pairs: z.array(pairSchema).min(1),
  costs: z.strictObject({
    groupSize: z.number().int().min(1),
    vehicles: z.number().int().min(1),
    /** Per vehicle per driving hour, for trips away from base. */
    perHourUsd: usdRange,
    /** Per vehicle per day (e.g. rental cars), or null. */
    dailyUsd: usdRange.nullable().default(null),
    dailyLabel: z.string().optional(),
    /** Per person per night by stay style (preference id) and base id. */
    accommodation: z.record(z.string(), z.record(z.string(), usdRange)),
  }),
  preferences: preferencesSchema,
  /** Extra tags that count as nightlife (family mode swaps them). */
  nightlifeTags: z.array(z.string()).default([]),
  /** Relabel trip highlights for this destination ({ temple: { one: "monastery", many: "monasteries" } }). */
  highlightLabels: z.record(z.string(), z.strictObject({ one: z.string(), many: z.string(), title: z.string().optional() })).default({}),
  theme: themeSchema,
});

export type TripPresetInput = z.input<typeof presetSchema>;
export type TripPreset = z.output<typeof presetSchema>;
export type PhotoSet = z.output<typeof photoSetSchema>;
export type PresetActivity = z.output<typeof activitySchema>;
export type PresetPair = z.output<typeof pairSchema>;
export type PresetRegion = z.output<typeof regionSchema>;
export type PresetBase = z.output<typeof baseSchema>;
export type PresetArea = z.output<typeof areaSchema>;
export type PresetLeg = z.output<typeof legSchema>;
export type PresetRoute = z.output<typeof routeSchema>;
export type PresetTransfer = z.output<typeof transferSchema>;
export type PresetSpecialDate = z.output<typeof specialDateSchema>;
export type PresetTheme = z.output<typeof themeSchema>;
export type ActivityVariant = z.output<typeof variantSchema>;
export type StayInCopy = z.output<typeof stayInCopySchema>;
export type Choice = z.output<typeof choice>;
